// Embeds the browser files (client/) into src/client-assets.js so the Worker can serve them
// without a separate upload, and lists the Worker-side features in src/features/index.js.
// Run after changing anything in client/ or adding a feature: npm run build
//
// Features:
//   client/features/<name>.js       editor code: feature('<name>', (core) => { ... });
//   client/features/<name>.ui.css   styles for the editor's own UI (shadow root)
//   client/features/<name>.page.css styles applied to the page while editing
//   src/features/<name>.js          Worker code: export default { name, api, routes, render, ... }
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { JUNK_TAG, JUNK_ATTR, JUNK_STYLE, JUNK_MARKER } from '../src/junk.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'client', f), 'utf8');
const list = (dir, re) => (existsSync(join(root, dir)) ? readdirSync(join(root, dir)).filter((f) => re.test(f)).sort() : []);

const featureJs = list('client/features', /^[a-z0-9-]+\.js$/);
const featureUiCss = list('client/features', /\.ui\.css$/);
const featurePageCss = list('client/features', /\.page\.css$/);

const uiCss = [read('ui.css'), ...featureUiCss.map((f) => `/* ${f} */\n${read(`features/${f}`)}`)].join('\n');
const pageCss = [read('editor.css'), ...featurePageCss.map((f) => `/* ${f} */\n${read(`features/${f}`)}`)].join('\n');
const featureCode = featureJs.map((f) => `  /* ---- feature: ${f} ---- */\n${read(`features/${f}`)}`).join('\n');

const junk = { tag: JUNK_TAG, attr: JUNK_ATTR, style: JUNK_STYLE, marker: JUNK_MARKER };
const editorJs = read('editor.js')
  .replace('__UI_CSS__', () => JSON.stringify(uiCss))
  .replace('__JUNK__', () => JSON.stringify(junk))
  .replace('/*__FEATURES__*/', () => featureCode);
for (const ph of ['__UI_CSS__', '__JUNK__', '/*__FEATURES__*/']) if (editorJs.includes(ph)) throw new Error(`${ph} placeholder not replaced`);
try { new Function(editorJs); } catch (err) { throw new Error(`editor.js does not parse after adding features: ${err.message}`); }

const files = { 'editor.js': editorJs, 'editor.css': pageCss, 'launcher.js': read('launcher.js') };
const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 10);

// Each asset is split into modules of at most CHUNK characters under src/client-assets/, so no source file in
// the engine (or the Claude plugin that bundles it) is larger than the plugin directory's 256 KiB file limit.
const CHUNK = 180 * 1024;
const chunkDir = join(root, 'src', 'client-assets');
rmSync(chunkDir, { recursive: true, force: true });
mkdirSync(chunkDir, { recursive: true });
const imports = [];
const entries = [];
for (const [name, text] of Object.entries(files)) {
  const parts = [];
  for (let i = 0; i < text.length;) {
    let end = Math.min(i + CHUNK, text.length);
    const c = text.charCodeAt(end - 1);
    if (end < text.length && c >= 0xd800 && c <= 0xdbff) end -= 1; // never split a surrogate pair
    parts.push(text.slice(i, end));
    i = end;
  }
  const base = name.replace(/\.(js|css)$/, '-$1');
  parts.forEach((part, n) => {
    const file = `${base}.${n}.js`;
    const id = `${base.replace(/-/g, '_')}_${n}`;
    writeFileSync(join(chunkDir, file), `// Generated by scripts/build-client.mjs. Do not edit by hand.\nexport default ${JSON.stringify(part)};\n`);
    imports.push(`import ${id} from './client-assets/${file}';\n`);
    parts[n] = id;
  });
  entries.push(`  ${JSON.stringify(name)}: ${parts.join(' + ') || '""'},\n`);
}
writeFileSync(join(root, 'src', 'client-assets.js'),
  `// Generated by scripts/build-client.mjs from client/. Do not edit by hand.\n`
  + imports.join('')
  + `export const CLIENT_VERSION = ${JSON.stringify(version)};\n`
  + `export const CLIENT = {\n${entries.join('')}};\n`);

mkdirSync(join(root, 'src', 'features'), { recursive: true });
const serverFeatures = list('src/features', /^[a-z0-9-]+\.js$/).filter((f) => f !== 'index.js');
const ident = (f) => `f_${f.replace(/\.js$/, '').replace(/-/g, '_')}`;
writeFileSync(join(root, 'src', 'features', 'index.js'),
  `// Generated by scripts/build-client.mjs from the files in this folder. Do not edit by hand.\n`
  + serverFeatures.map((f) => `import ${ident(f)} from './${f}';\n`).join('')
  + `export const FEATURES = [${serverFeatures.map(ident).join(', ')}];\n`);

console.log(`client assets built (${version}); features: client [${featureJs.join(', ') || 'none'}], worker [${serverFeatures.join(', ') || 'none'}]`);
